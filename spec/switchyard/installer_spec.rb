# frozen_string_literal: true

require "spec_helper"
require "tmpdir"
require "yaml"
require "switchyard/installer"

RSpec.describe Switchyard::Installer do
  subject(:installer) { described_class.new(destination: temp_dir, runner: runner) }

  let(:temp_dir) { Dir.mktmpdir }
  let(:runner) { instance_double("Switchyard::ProcessRunner") }

  after do
    FileUtils.remove_entry(temp_dir)
  end

  describe "#install!" do
    context "when destination is a Rails project" do
      before do
        FileUtils.mkdir_p(File.join(temp_dir, "config"))
        File.write(File.join(temp_dir, "config", "database.yml"), "development:\n  database: test_dev\n")
        FileUtils.mkdir_p(File.join(temp_dir, "bin"))
      end

      it "generates binstubs in bin/ for switchyard, dev, staging, production, and pr" do
        installer.install!

        %w[switchyard dev staging production pr].each do |binstub|
          path = File.join(temp_dir, "bin", binstub)
          expect(File.exist?(path)).to be true
          expect(File.stat(path).executable?).to be true
        end
        expect(installer.generated_binstubs).to eq(%w[switchyard dev staging production pr])
        expect(installer.preserved_binstubs).to eq([])
      end

      it "preserves an existing non-Switchyard bin/dev launcher while still generating other binstubs" do
        custom_dev = "#!/usr/bin/env sh\nexec foreman start -f Procfile.dev \"$@\"\n"
        dev_path = File.join(temp_dir, "bin", "dev")
        File.write(dev_path, custom_dev)

        installer.install!

        expect(File.read(dev_path)).to eq(custom_dev)
        expect(installer.preserved_binstubs).to eq(["dev"])
        expect(installer.generated_binstubs).to eq(%w[switchyard staging production pr])
        %w[switchyard staging production pr].each do |binstub|
          expect(File.exist?(File.join(temp_dir, "bin", binstub))).to be true
        end
      end

      it "updates bin/dev when the existing bin/dev was generated by Switchyard" do
        dev_path = File.join(temp_dir, "bin", "dev")
        File.write(dev_path, "#!/usr/bin/env ruby\n# old Switchyard::CLI stub\n")

        installer.install!

        expect(File.read(dev_path)).to include("Switchyard::CLI.start")
        expect(installer.preserved_binstubs).to eq([])
        expect(installer.generated_binstubs).to include("dev")
      end

      it "creates a default .switchyard.yml configuration file" do
        installer.install!

        config_path = File.join(temp_dir, ".switchyard.yml")
        expect(File.exist?(config_path)).to be true
        expect(File.read(config_path)).to include("adapter: railway")
      end

      context "when git_safe option is enabled" do
        subject(:installer) { described_class.new(destination: temp_dir, runner: runner, git_safe: true) }

        it "creates .git/safe if destination is a git repository" do
          FileUtils.mkdir_p(File.join(temp_dir, ".git"))
          installer.install!

          expect(Dir.exist?(File.join(temp_dir, ".git", "safe"))).to be true
          expect(installer.git_safe_enabled?).to be true
        end

        it "does not raise if destination is not a git repository" do
          installer.install!

          expect(installer.git_safe_enabled?).to be false
        end
      end

      context "when git_safe option is disabled (default)" do
        it "does not create .git/safe even if destination is a git repository" do
          FileUtils.mkdir_p(File.join(temp_dir, ".git"))
          installer.install!

          expect(Dir.exist?(File.join(temp_dir, ".git", "safe"))).to be false
          expect(installer.git_safe_enabled?).to be false
        end
      end

      context "when github_action option is enabled" do
        subject(:installer) { described_class.new(destination: temp_dir, runner: runner, github_action: true) }

        it "auto-populates RAILWAY_PROJECT_ID when railway status returns a project ID" do
          expect(runner).to receive(:capture).with(
            "railway", "status", "--json"
          ).once.and_return(['{"id":"proj-123","name":"MyApp"}', double(success?: true)])

          installer.install!
          expect(installer.railway_project_id).to eq("proj-123")

          workflow_path = File.join(temp_dir, ".github", "workflows", "switchyard-cleanup-pr.yml")
          expect(File.exist?(workflow_path)).to be true

          content = File.read(workflow_path)
          parsed = YAML.safe_load(content)
          expect(parsed["name"]).to eq("Switchyard Cleanup PR Environment")

          cleanup_step = parsed.dig("jobs", "cleanup", "steps").find { |step| step["name"] == "Decommission Railway PR Environment" }
          expect(cleanup_step).not_to be_nil
          expect(cleanup_step["env"]).to eq(
            "RAILWAY_API_TOKEN" => "${{ secrets.RAILWAY_API_TOKEN }}",
            "RAILWAY_PROJECT_ID" => "${{ secrets.RAILWAY_PROJECT_ID || vars.RAILWAY_PROJECT_ID || 'proj-123' }}"
          )
          expect(content).not_to include("RAILWAY_TOKEN:")
          expect(content).not_to include("secrets.RAILWAY_TOKEN")

          run_script = cleanup_step["run"]
          expect(run_script).to include('if [ -z "$RAILWAY_API_TOKEN" ]; then')
          expect(run_script).to include('if [ -z "$RAILWAY_PROJECT_ID" ]; then')
          expect(run_script).to include('railway link --project "$RAILWAY_PROJECT_ID" --environment production')
          expect(run_script).to include("railway environment list --json")
          expect(run_script).to include("jq -e --arg name")
          expect(run_script).to include("exit 0")
          expect(run_script).to include('railway environment delete "$ENV_NAME" --yes')
          expect(installer.github_action_generated?).to be true
        end

        it "falls back to GitHub secret/var expression when railway status is unlinked" do
          expect(runner).to receive(:capture).with(
            "railway", "status", "--json"
          ).once.and_return(["Project not found", double(success?: false)])

          installer.install!
          expect(installer.railway_project_id).to be_nil

          workflow_path = File.join(temp_dir, ".github", "workflows", "switchyard-cleanup-pr.yml")
          parsed = YAML.safe_load_file(workflow_path)
          cleanup_step = parsed.dig("jobs", "cleanup", "steps").find { |step| step["name"] == "Decommission Railway PR Environment" }
          expect(cleanup_step["env"]).to eq(
            "RAILWAY_API_TOKEN" => "${{ secrets.RAILWAY_API_TOKEN }}",
            "RAILWAY_PROJECT_ID" => "${{ secrets.RAILWAY_PROJECT_ID || vars.RAILWAY_PROJECT_ID }}"
          )
        end
      end

      context "when github_action option is disabled (default)" do
        it "does not create the workflow file" do
          installer.install!

          workflow_path = File.join(temp_dir, ".github", "workflows", "switchyard-cleanup-pr.yml")
          expect(File.exist?(workflow_path)).to be false
          expect(installer.github_action_generated?).to be false
        end
      end
    end

    describe "#github_secrets_url" do
      context "with an SSH GitHub remote" do
        it "returns the direct URL to add actions secrets" do
          expect(runner).to receive(:capture).with(
            "git", "remote", "get-url", "origin"
          ).and_return(["git@github.com:LoganDSPrice/NBA-Over-Under-Redux.git\n", double(success?: true)])

          expect(installer.github_secrets_url).to eq(
            "https://github.com/LoganDSPrice/NBA-Over-Under-Redux/settings/secrets/actions"
          )
        end
      end

      context "with an HTTPS GitHub remote" do
        it "returns the direct URL to add actions secrets" do
          expect(runner).to receive(:capture).with(
            "git", "remote", "get-url", "origin"
          ).and_return(["https://github.com/LoganDSPrice/NBA-Over-Under-Redux.git\n", double(success?: true)])

          expect(installer.github_secrets_url).to eq(
            "https://github.com/LoganDSPrice/NBA-Over-Under-Redux/settings/secrets/actions"
          )
        end
      end

      context "when remote is not GitHub" do
        it "returns nil" do
          expect(runner).to receive(:capture).with(
            "git", "remote", "get-url", "origin"
          ).and_return(["git@gitlab.com:user/project.git\n", double(success?: true)])

          expect(installer.github_secrets_url).to be_nil
        end
      end

      context "when git command fails" do
        it "returns nil" do
          expect(runner).to receive(:capture).with(
            "git", "remote", "get-url", "origin"
          ).and_return(["fatal: not a git repository", double(success?: false)])

          expect(installer.github_secrets_url).to be_nil
        end
      end
    end

    describe "RAILWAY_ACCOUNT_TOKENS_URL" do
      it "points to Railway account tokens rather than project tokens" do
        expect(described_class::RAILWAY_ACCOUNT_TOKENS_URL).to eq("https://railway.com/account/tokens")
      end
    end

    describe "#railway_project_id" do
      context "when railway status returns nested project id" do
        let(:json_output) do
          <<~JSON
            {
              "project": { "id": "proj-123", "name": "MyApp" },
              "environment": { "id": "env-456", "name": "production" }
            }
          JSON
        end

        it "extracts the project id" do
          expect(runner).to receive(:capture).with(
            "railway", "status", "--json"
          ).and_return([json_output, double(success?: true)])

          expect(installer.railway_project_id).to eq("proj-123")
        end
      end

      context "when railway status returns standard root project schema" do
        let(:json_output) do
          <<~JSON
            {
              "id": "e6cef8da-25b2-4aaa-a7cb-22406df4eeb6",
              "name": "OverUnder",
              "environments": {
                "edges": [
                  {
                    "node": {
                      "id": "6d8b8757-d8dd-4346-87e2-f373e05dbfc3",
                      "name": "production"
                    }
                  }
                ]
              }
            }
          JSON
        end

        it "extracts root project id" do
          expect(runner).to receive(:capture).with(
            "railway", "status", "--json"
          ).and_return([json_output, double(success?: true)])

          expect(installer.railway_project_id).to eq("e6cef8da-25b2-4aaa-a7cb-22406df4eeb6")
        end

        it "extracts JSON cleanly even when CLI output contains update banners or warnings" do
          banner_output = "New version available: v5.71.0 visit https://docs.railway.com\n#{json_output}\nTip: Run update"
          expect(runner).to receive(:capture).with(
            "railway", "status", "--json"
          ).and_return([banner_output, double(success?: true)])

          expect(installer.railway_project_id).to eq("e6cef8da-25b2-4aaa-a7cb-22406df4eeb6")
        end
      end

      context "when railway CLI command fails or project is unlinked" do
        it "returns nil" do
          expect(runner).to receive(:capture).with(
            "railway", "status", "--json"
          ).and_return(["Project not found", double(success?: false)])

          expect(installer.railway_project_id).to be_nil
        end
      end

      context "when railway CLI returns invalid JSON" do
        it "returns nil" do
          expect(runner).to receive(:capture).with(
            "railway", "status", "--json"
          ).and_return(["not json", double(success?: true)])

          expect(installer.railway_project_id).to be_nil
        end
      end
    end

    describe "#link_project!" do
      subject(:installer) { described_class.new(destination: temp_dir, runner: runner, github_action: true) }

      before do
        FileUtils.mkdir_p(File.join(temp_dir, "config"))
        File.write(File.join(temp_dir, "config", "database.yml"), "development:\n  database: test_dev\n")
        FileUtils.mkdir_p(File.join(temp_dir, "bin"))
      end

      it "runs railway link, refreshes railway_project_id, and regenerates the cleanup workflow when linking succeeds" do
        expect(runner).to receive(:capture).with("railway", "status", "--json").and_return(
          ["Project not found", double(success?: false)],
          ['{"id":"proj-linked","name":"MyApp"}', double(success?: true)]
        )
        expect(runner).to receive(:system).with("railway", "link").and_return(true)

        installer.install!
        expect(installer.railway_project_id).to be_nil

        expect(installer.link_project!).to be(true)
        expect(installer.railway_project_id).to eq("proj-linked")

        workflow_path = File.join(temp_dir, ".github", "workflows", "switchyard-cleanup-pr.yml")
        parsed = YAML.safe_load_file(workflow_path)
        cleanup_step = parsed.dig("jobs", "cleanup", "steps").find { |step| step["name"] == "Decommission Railway PR Environment" }
        expect(cleanup_step["env"]["RAILWAY_PROJECT_ID"]).to eq(
          "${{ secrets.RAILWAY_PROJECT_ID || vars.RAILWAY_PROJECT_ID || 'proj-linked' }}"
        )
      end

      it "returns false and leaves workflow unchanged when railway link fails" do
        expect(runner).to receive(:capture).with("railway", "status", "--json").once.and_return(
          ["Project not found", double(success?: false)]
        )
        expect(runner).to receive(:system).with("railway", "link").and_return(false)

        installer.install!
        expect(installer.link_project!).to be(false)
        expect(installer.railway_project_id).to be_nil
      end
    end

    context "when destination is not a Rails directory" do
      it "raises a NotInRailsProjectError" do
        expect do
          installer.install!
        end.to raise_error(Switchyard::Installer::NotInRailsProjectError, /Rails project/i)
      end
    end
  end
end
